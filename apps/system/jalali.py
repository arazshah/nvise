from __future__ import annotations

from datetime import date, datetime


def _gregorian_to_jalali(gy: int, gm: int, gd: int) -> tuple[int, int, int]:
    g_d_m = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]
    gy2 = gy + 1 if gm > 2 else gy
    days = (
        355666
        + (365 * gy)
        + ((gy2 + 3) // 4)
        - ((gy2 + 99) // 100)
        + ((gy2 + 399) // 400)
        + gd
        + g_d_m[gm - 1]
    )
    jy = -1595 + (33 * (days // 12053))
    days %= 12053
    jy += 4 * (days // 1461)
    days %= 1461
    if days > 365:
        jy += (days - 1) // 365
        days = (days - 1) % 365
    if days < 186:
        jm = 1 + (days // 31)
        jd = 1 + (days % 31)
    else:
        jm = 7 + ((days - 186) // 30)
        jd = 1 + ((days - 186) % 30)
    return jy, jm, jd


def format_jalali(value: date | datetime | None, include_time: bool = False) -> str:
    if value is None:
        return "—"
    jy, jm, jd = _gregorian_to_jalali(value.year, value.month, value.day)
    result = f"{jy:04d}/{jm:02d}/{jd:02d}"
    if include_time and isinstance(value, datetime):
        result += f" {value.hour:02d}:{value.minute:02d}"
    return result
